create table if not exists public.groundquote_feedback (
  id bigint generated by default as identity primary key,
  answer_id uuid not null unique,
  rating text not null check (rating in ('helpful', 'not_helpful')),
  answer_mode text not null check (answer_mode in ('generated', 'extractive')),
  created_at timestamptz not null default now()
);

alter table public.groundquote_feedback enable row level security;

-- The app writes through a server-only service role key. Browser clients get no policy.
revoke all on public.groundquote_feedback from anon, authenticated;
